# What each language calls the 11 languages (for "Shall I call them in Marathi?" said in Tamil)
LANGUAGE_NAMES = languages.LANGUAGE_NAMES

BROWSER_KEYS = ("searching", "found", "none", "calling", "quoted", "hidden", "hold", "slot", "walk", "failed",
                "nodeal", "recommend", "nobody", "confirmed", "pick", "unknown", "stopped", "no_location", "choose",
                "recommended", "confirmed_k", "confirm_btn", "other_btn", "deal_title", "appt_title", "paid_title",
                "all_inclusive", "saved", "advance", "released", "calling_back", "paid_separately", "fee", "fee_tbc",
                "send_wa", "sent_wa", "pay", "at_actuals")


def code(language: str) -> str:
    return language if language in LINES else "en"


def line(user_language: str, key: str, /, **kwargs) -> str:
    """One user-facing line. Rupee placeholders take ints (₹ with Indian grouping); the rest take text."""
    from app.pricing import format_inr  # local import: pricing imports nothing from here
    template = LINES[code(user_language)].get(key) or LINES["en"][key]
    return template.format(**{k: format_inr(v) if k in MONEY and isinstance(v, (int, float)) else v
                              for k, v in kwargs.items()})


def chips(user_language: str, key: str, /, **kwargs) -> list[str]:
    return line(user_language, key, **kwargs).split("|")


def language_name(user_language: str, call_language: str) -> str:
    """How the user's language names the call language ('Marathi', 'मराठी', 'மராத்தி')."""
    names = LANGUAGE_NAMES[code(user_language)]
    return names.get(call_language) or names["hi"]


def unit_phrase(language: str, unit: str) -> str:
    """' per month' / ' (प्रति महीना)' after 'what's your budget', or '' for a one-off job."""
    words = lexicon.unit(code(language), unit) if unit and unit != "flat" else ""
    if not words:
        return ""
    return f" {words}" if code(language) == "en" else f" ({words})"


def browser_lines(language: str) -> dict:
    """What the browser needs to narrate the calls and show the result in the user's language."""
    table = LINES[code(language)]
    return {"code": code(language), "lines": {k: table[k] for k in BROWSER_KEYS},
            "language_names": LANGUAGE_NAMES[code(language)]}


_PUNCT_RE = re.compile(r"[\s.,!?;:\"'()\[\]–—।॥📍]+")


def _norm(text: str) -> str:
    return _PUNCT_RE.sub(" ", (text or "").lower()).strip()


def matches_chip(text: str, key: str) -> bool:
    """Is this message one of the tap-to-say suggestions for `key`, in any language?"""
    t = _norm(text)
    return bool(t) and any(t == _norm(LINES[lang][key]) for lang in LINES)
